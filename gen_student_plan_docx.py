def _set_font(run, size=12, bold=False, color=None, name='宋体'):
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.font.bold = bold
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    if color:
        run.font.color.rgb = RGBColor(*color)

def _add_runs(para, text, size=12, bold=False, color=None, name='宋体'):
    """支持行内 **强调** 语法：按 ** 切分，奇数段渲染为加粗。无 ** 时等价于单 run。"""
    for i, seg in enumerate(str(text).split('**')):
        if seg:
            _set_font(para.add_run(seg), size, bold or (i % 2 == 1), color, name)

def h1(text):
    # 用内置 Heading 1 样式（不是手工加粗的 Normal）：Word 导航窗格、自动目录、交叉引用才认
    para = doc.add_paragraph(style='Heading 1')
    _set_font(para.add_run(text), 15, True, (0x1F, 0x3A, 0x5F), '黑体')
    pf = para.paragraph_format
    pf.space_before, pf.space_after = Pt(16), Pt(8)
    pf.keep_with_next = True
    return para

def h2(text):
    para = doc.add_paragraph(style='Heading 2')
    _set_font(para.add_run(text), 13, True, (0x2C, 0x4A, 0x75), '黑体')
    pf = para.paragraph_format
    pf.space_before, pf.space_after = Pt(10), Pt(5)
    pf.keep_with_next = True
    return para

def p(text, bold=False, size=12, indent=True):
    para = doc.add_paragraph()
    if indent:
        para.paragraph_format.first_line_indent = Pt(24)
    _add_runs(para, text, size, bold)
    para.paragraph_format.space_after = Pt(4)
    para.paragraph_format.line_spacing = 1.3

def bullet(text, bold_prefix=None):
    para = doc.add_paragraph()
    para.paragraph_format.left_indent = Pt(18)
    para.paragraph_format.space_after = Pt(3)
    para.paragraph_format.line_spacing = 1.3
    if bold_prefix:
        _set_font(para.add_run('· ' + bold_prefix), 12, True)
        _add_runs(para, text, 12)
    else:
        _add_runs(para, '· ' + text, 12)

def table(headers, rows, widths=None, fontsize=10.5):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    for j, htxt in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.text = ''
        _set_font(cell.paragraphs[0].add_run(htxt), fontsize, True, name='黑体')
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.rows[i + 1].cells[j]
            cell.text = ''
            _add_runs(cell.paragraphs[0], val, fontsize)
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Mm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)

