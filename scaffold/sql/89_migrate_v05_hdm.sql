BEGIN;

-- ═══════════════════════════════════════════════════════════════════════════
-- 背景 —— 一条**被推翻的"不做"**
-- ═══════════════════════════════════════════════════════════════════════════
-- 10_ddl_v0.5.sql 文件头原写着：
--   「待办：第二批（横断面/路基土方/构造物）顺延至 v0.5 …
--     其中「横断面地面线（.HDM）」经确认**不做**（用户指示）。」
--
-- 2026-09 用户改判为**要做**。★改判的理由与"它是地面线还是设计面"**无关**：
--   M2 的 .HDM 解析器**能**解析出 `cross_section` 段，而平台**没有对应的表** ——
--   解析出来的数据没有地方存，**解析完就丢**。
--   「段能解析、表不存在」= **静默丢数据**，这比明说"不做"更糟。
--   （对照：.3DR 是"源里根本没有文件"，.BDM/.HDMSJ 是"结构上读不了"，
--     都记在 design_file.parse_status 里，是**看得见的**不做；这一条是看不见的。）
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 定性 —— 三份独立证据一致：这是**外业测量**的横断面地面线，不是设计面
-- ═══════════════════════════════════════════════════════════════════════════
--   ① 教程 §13.8 首句：「此文件记录**外业横断面测量**的成果数据。」
--      同节格式说明：「以下每三行数据记录一个桩号断面，其中第一行是断面的中桩号，
--      第二行和第三行分别记录左侧和右侧横断面的数据；首先是每侧的总点数，后面是
--      每一测量位置相对与前一位置的平距和高差。」
--   ② 本工程文件名：「052201341刘其立道路毕设**横断面地面线文件**.HDM」
--   ③ 文件内容实测（333 断面 / 2215 测点）：
--        高差  min −30.994  max +22.976  中位 0.075  均值 0.395
--        平距  min   0.019  max  50.000  中位 12.389
--        |高差| > 2 m 的测点 878 个（39.6%）
--      高差能到 ±31 m 是**地形起伏**的量级；路基设计面的填挖高差不会如此。
--      （横断面**设计**成果在 .tf 里 —— §13.9「记录桩号、填挖方断面面积、左右侧坡口
--        坡脚至中桩的距离等数据」，已由 J1 earthwork_section 承接，332 行。）
--
-- ★ 表名照内容走：cross_section_ground_point。
--   与 profile_ground_point（← .DMX **纵**断面地面线，扁平表）同构，
--   一纵一横，同族不同剖面。
--
-- ═══════════════════════════════════════════════════════════════════════════
-- 两处**故意不照抄** profile_ground_point（各有实测依据，不是随手）
-- ═══════════════════════════════════════════════════════════════════════════
--   ① **不用 station_id 外键**
--      profile_ground_point 用 `station_id bigint NOT NULL UNIQUE REFERENCES
--      station_sequence(id)`，因为 .DMX 的桩号**恰好是** station_sequence 的子集。
--      .HDM **不是**。实测（section_id=6）：
--          .HDM              333 个断面
--          station_sequence  332 行
--          .HDM 有、库无 → 5701.461（1 个）   ｜   库有、.HDM 无 → 0 个
--      就多这一个，也不能用外键。故照 I/J 节里 .CTR/.SUP/.WID 的规矩直接带 station_km。
--      （J 节能用 station_id，因为 .tf/.lj 正好 332 行。）
--
--   ② **不建父表**
--      一个桩号 → 左右两侧 → 每侧若干测点，看着是三层，但
--      (section_id, station_km, side, seq_no) 一个四元组就能唯一定位一个测点。
--      父表能提供的信息（每侧几个点、每断面几个点）是 COUNT(*) **派生量**，
--      按仓库铁律「存设计输入、导出派生量」不落列。
--
-- ★ 只存**增量**：文件给的是「相对与前一位置的平距和高差」，这里原样存。
--    累积平距、累积高差、各测点绝对高程都是**派生量**，不落列。
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS cross_section_ground_point (
    id           bigint        generated always as identity primary key,
    section_id   bigint        not null references road_section(id),
    station_km   numeric(12,6) not null,   -- 精度标准 1 mm，与全库其余 32 处 station*_km 一致
    side         char(1)       not null check (side in ('L','R')),   -- ⚠ 历史写法，见文末注

    seq_no       smallint      not null,   -- 该侧第几个测点，从 1 起
    offset_m     numeric(10,4) not null,   -- 相对**前一测点**的平距（文件原样）
    elev_diff_m  numeric(10,4) not null,   -- 相对**前一测点**的高差（文件原样，上正下负）
    remark       text,
    constraint uq_cross_section_ground_point unique (section_id, station_km, side, seq_no)
);

comment on table cross_section_ground_point is
  '逐桩横断面地面线测点（纬地 .HDM，教程 §13.8）。一个桩号左右两侧各若干测点，一行一个测点。'
  '★这是**外业测量**的地面线，不是设计面（三份证据见 89_migrate_v05_hdm.sql 抬头）。'
  '★只存文件给的**增量**（相对前一测点的平距/高差）；累积值与绝对高程是派生量，不落列。'
  '★不用 station_id 外键：实测 .HDM 有 333 个断面而 station_sequence 只有 332 个'
  '（多 5701.461），不是子集，故照 .CTR/.SUP/.WID 的规矩直接带 station_km。';

comment on column cross_section_ground_point.station_km is
  '断面中桩号（.HDM 每三行里的第 1 行），单位 km，numeric(12,6) = 1 mm。'
  '本工程实测 333 个断面，范围 0.000 ~ 5.805421 km。';

comment on column cross_section_ground_point.side is
  'L = 左侧（每三行的第 2 行），R = 右侧（第 3 行）。教程 §13.8 原文：'
  '「第二行和第三行分别记录左侧和右侧横断面的数据」。';

comment on column cross_section_ground_point.seq_no is
  '该侧第几个测点，从 1 起，顺序与文件中的测量顺序一致。'
  '★每侧点数**不落列** —— 它是该侧 seq_no 的 COUNT(*)，属派生量。';

comment on column cross_section_ground_point.offset_m is
  '相对**前一测点**的平距 m（文件原样，**非累积值**）。第一个测点的"前一测点"是中桩。'
  '实测 2215 个测点：平距 0.019 ~ 50.000 m，中位 12.389 m。累积平距是派生量。';

comment on column cross_section_ground_point.elev_diff_m is
  '相对**前一测点**的高差 m（文件原样，上正下负，**非累积值**）。'
  '实测 −30.994 ~ +22.976 m，中位 0.075 m；39.6% 的测点 |高差| > 2 m —— '
  '这个量级正是"地形起伏"，也是判定本文件是**地面线**而非设计面的依据之一。'
  '累积高差与各测点绝对高程都是派生量，不落列。';

COMMIT;

