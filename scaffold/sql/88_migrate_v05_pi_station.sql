-- v0.5 迁移 ⑧⑧：alignment_pi 补 station_km（交点桩号）
--
-- 背景 —— **一个被推翻的"派生量"判断**：
--   alignment_pi 原注释写着「交点桩号 = ZH + 切线长，是**派生量**，故 DDL 里没有它的列」。
--   这话本身没错（它确实可由 ZH + T 算出），但**结论错了**：.JD 文件本来就给出这个值
--   （第 3 列「本点桩号」，适配器 jd.py 的 f10[0] 已经在读，只是没往下传）。
--   —— "可派生"不等于"源里没有"。凡是源里给了的，就该存下来，否则：
--     ① 源与推导的差异永远暴露不出来（没有第二个值可比）；
--     ② 下游按桩号寻址时，这张表是**唯一**没有桩号列的表。
--
-- 实测（本工程 section_id=6，8 个交点）：
--   派生值（ZH + 切线长）与 .JD 的值逐个吻合，差 6e-9 ~ 2.4e-8 m —— 纯浮点噪声。
--   所以两条路**互相独立**且一致，正好用来对账（verify ② 已在做，用的是米）。
--
-- 单位：DDL 与全库同族列一致，存**公里**；对账在 design_import 里用米（_station_m）。
-- ⚠ 精度必须 numeric(12,6)（1 mm），与全库其余 31 处 station*_km 同一标准 ——
--   v0.5 落 earthwork_section 时正是在这里踩过 numeric(10,4) 的坑。
-- ═══════════════════════════════════════════════════════════════════════════════

begin;

alter table alignment_pi add column if not exists station_km numeric(12,6);

comment on column alignment_pi.station_km is
  '交点桩号（.JD 第 3 列「本点桩号」，原始量）。原注释称其为派生量故不建列，前提有误：'
  '.JD 本就给出该值，实测 8/8 与派生值吻合（差 ≤2.4e-8 m）。两条路互相独立，用于对账。';

-- 已有数据回填：由已有的内部值算不出来（库里没存 _station_m），
-- 故这里用同表可得的等价关系回填：交点桩号 = ZH 桩号 + 切线长。
-- 但 ZH 桩号在 alignment_element 里，需按 section 关联 —— 为了不在这里重写几何，
-- 采取更稳的做法：**要求重跑一次导入**（幂等），由 design_import 写入。
-- 若只想原地补：下面的 UPDATE 用 tangent_len_m 反推不了 ZH，故意不做，
-- 免得留下一个"看起来填上了、其实是猜的"值。
--   → 正确姿势：cd scaffold && uv run ... .tmp/ctr_load.py --write

commit;
